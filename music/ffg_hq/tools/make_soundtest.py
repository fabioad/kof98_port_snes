#!/usr/bin/env python3
"""Build the standalone FFG HQ sound test ROM (music/ffg_hq/soundtest).

Soundbank order: modules 0..16 are the new conversions (music/ffg_hq/it),
17..33 the modules the game ships now (the exact payloads of the current
build, after it_pattern_limit).  Nothing in the game build is touched.
"""
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
ROOT = HERE.parents[1]
ST = HERE / 'soundtest'
SDK = Path('/run/media/fabio/Dados/Fabio/pvsneslib-sdk-4.6')
SMCONV = SDK / 'devkitsnes/tools/smconv'
sys.path.insert(0, str(ROOT / 'tools'))
from approved_music import PACK, modules                          # noqa: E402
from it_pattern_limit import fit_snesmod                          # noqa: E402

# (module, label shown on screen)
SONGS = [
    ('menu_kof', 'TITULO   KOF'),
    ('menu_cipher', 'MENU     CIPHER'),
    ('menu_cipher_beta', 'MENU     CIPHER BETA'),
    ('menu_lastdance', 'MENU     LAST DANCE'),
    ('menu_sunset', 'MENU     SUNSET'),
    ('menu_winner', 'VITORIA  W'),
    ('menu_crystal', 'FINAL    CRYSTAL'),
    ('stg0', 'FASE 0   ESAKA'),
    ('stg1', 'FASE 1   DORA'),
    ('stg2', 'FASE 2   ARASHI'),
    ('stg3', 'FASE 3   S.TOWN'),
    ('stg4', 'FASE 4   RUMBLING'),
    ('stg5', 'FASE 5   RUGAL'),
    ('stg6', 'FASE 6   FAIRY'),
    ('stg7', 'FASE 7   SLUM'),
    ('stg8', 'FASE 8   RYU-KO'),
    ('stg9', 'FASE 9   KURIKINTON'),
]


def main():
    its = ST / 'it'
    shutil.rmtree(its, ignore_errors=True)
    its.mkdir(parents=True)
    approved = {Path(r['file']).stem: r for r in modules()}
    files = []
    for i, (name, _) in enumerate(SONGS):
        dst = its / f'n{i:02d}_{name}.it'
        shutil.copyfile(HERE / 'it' / f'{name}.it', dst)
        files.append(dst)
    for i, (name, _) in enumerate(SONGS):
        dst = its / f'a{i:02d}_{name}.it'
        # same payload approved_music.install() gives the game build
        dst.write_bytes(fit_snesmod((PACK / approved[name]['file']).read_bytes()))
        files.append(dst)

    (ST / 'res').mkdir(exist_ok=True)
    rel = [str(f.relative_to(ST)) for f in files]
    subprocess.run([str(SMCONV), '-s', '-o', 'res/soundbank', '-V', '-b', '5', *rel],
                   cwd=ST, check=True, stdout=subprocess.DEVNULL)
    asm = (ST / 'res/soundbank.asm').read_text()
    banks = sorted({int(n) for n in re.findall(r'SOUNDBANK__(\d+)', asm)})
    assert banks == list(range(len(banks))), banks

    h = ['/* generated by music/ffg_hq/tools/make_soundtest.py */',
         f'#define NSONGS {len(SONGS)}', '']
    h += ['extern char %s;' % ', '.join(f'SOUNDBANK__{b}' for b in banks), '']
    h.append('static const char *names[NSONGS] = {')
    h += [f'    "{label}",' for _, label in SONGS]
    h += ['};', '', 'static void registerBanks(void)', '{',
          '    /* banks must be registered last-to-first */']
    h += [f'    spcSetBank(&SOUNDBANK__{b});' for b in reversed(banks)]
    h += ['}', '']
    (ST / 'songs.h').write_text('\n'.join(h))

    rombanks = 5 + len(banks) + 1
    size = 1
    while size < rombanks:
        size *= 2
    romsize = {16: 0x09, 32: 0x0A, 64: 0x0B, 128: 0x0C}[max(16, size)]
    (ST / 'romsize.mk').write_text(
        f'ROMBANKS := {max(16, size)}\nROMSIZE := {romsize:02X}\n')
    print(f'{len(files)} modules, {len(banks)} sound banks, ROM {max(16, size) * 32} KB')

    env = dict(PVSNESLIB_HOME=str(SDK))
    import os
    env = {**os.environ, **env}
    subprocess.run(['make', '-C', str(ST), 'clean'], env=env,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    subprocess.run([str(SMCONV), '-s', '-o', 'res/soundbank', '-V', '-b', '5', *rel],
                   cwd=ST, check=True, stdout=subprocess.DEVNULL)
    r = subprocess.run(['make', '-C', str(ST)], env=env, capture_output=True, text=True)
    print(r.stdout[-1500:], r.stderr[-1500:])
    r.check_returncode()
    out = ROOT / 'kof98-ffg-soundtest.sfc'
    shutil.copyfile(ST / 'soundtest.sfc', out)
    print('->', out)


if __name__ == '__main__':
    main()
