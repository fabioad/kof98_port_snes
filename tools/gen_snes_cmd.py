def normals_entries(n):
    out = []
    out.append((f"Stand Light Punch", n["lp"], "x",
                'triggerall = command != "holddown"\ntrigger1 = statetype = S\ntrigger1 = ctrl\n'))
    out.append((f"Stand Strong Punch", n["hp"], "y",
                'triggerall = command != "holddown"\ntrigger1 = statetype = S\ntrigger1 = ctrl\n'))
    out.append((f"Stand Light Kick", n["lk"], "a",
                'triggerall = command != "holddown"\ntrigger1 = statetype = S\ntrigger1 = ctrl\n'))
    out.append((f"Stand Strong Kick", n["hk"], "b",
                'triggerall = command != "holddown"\ntrigger1 = statetype = S\ntrigger1 = ctrl\n'))
    for nm, v, btn in (("Crouching Light Punch", n["clp"], "x"),
                       ("Crouching Strong Punch", n["chp"], "y"),
                       ("Crouching Light Kick", n["clk"], "a"),
                       ("Crouching Strong Kick", n["chk"], "b")):
        out.append((nm, v, btn,
                    'triggerall = command = "holddown"\ntrigger1 = statetype = C\ntrigger1 = ctrl\n'))
    for nm, v, btn in (("Jump Light Punch", n["jlp"], "x"),
                       ("Jump Strong Punch", n["jhp"], "y"),
                       ("Jump Light Kick", n["jlk"], "a"),
                       ("Jump Strong Kick", n["jhk"], "b")):
        out.append((nm, v, btn,
                    'trigger1 = statetype = A\ntrigger1 = ctrl\n'))
    return out


def gen(name, spec):
    buf = [HEADER.format(name=name)]
    buf.append("[Statedef -1]\n\n")
    # command defs come first?  parse_cmd scans whole file for [Command]
    # blocks -- keep them BEFORE [Statedef -1] like Kyo_SNES.cmd does.
    cmds = "".join(cmd_block(n, m, t) for n, m, t in CMDS)
    body = []

    for nm, v, mot, extra in spec["specials"]:
        body.append(st(nm, v, mot, extra))

    rolls = spec["rolls"]
    if rolls:
        esqf, esqb, esql, dodge, maxb, charge = rolls
        if charge:
            body.append(st("Fusion Charge", charge, "CHARGE",
                           "triggerall = statetype = S\ntrigger1 = ctrl\n"))
        if maxb:
            body.append(st("Fusion MAX Activate", maxb, "MAX_ON",
                           "triggerall = statetype = S\ntrigger1 = ctrl\n"))
        if esqf:
            body.append(st("Fusion Roll Fwd", esqf, "ESQ_F",
                           "triggerall = statetype = S\ntrigger1 = ctrl\n"))
        if esqb:
            body.append(st("Fusion Roll Back", esqb, "ESQ_B",
                           "triggerall = statetype = S\ntrigger1 = ctrl\n"))
        if esql:
            body.append(st("Fusion Extra Dodge", esql, "ESQ_L",
                           'triggerall = command != "holdfwd"\n'
                           'triggerall = command != "holdback"\n'
                           "triggerall = statetype = S\ntrigger1 = ctrl\n"))
        if dodge:
            body.append(st("Extra Dodge Buttons", esql or dodge, "DODGE",
                           "triggerall = statetype = S\ntrigger1 = ctrl\n"))

    if spec["cd"]:
        body.append(st("Blowback Attack", spec["cd"], "CD",
                       "triggerall = statetype != A\ntrigger1 = ctrl\n"))

    body.append(st("Run Fwd", 100, None,
                   'trigger1 = command = "FF"\ntrigger1 = statetype = S\ntrigger1 = ctrl\n'))
    body.append(st("Run Back", 105, None,
                   'trigger1 = command = "BB"\ntrigger1 = statetype = S\ntrigger1 = ctrl\n'))

    body.append(
        "[State -1, Throw]\ntype = ChangeState\nvalue = %d\n"
        'triggerall = command = "y"\ntriggerall = statetype = S\n'
        "triggerall = ctrl\n"
        'trigger1 = command = "holdfwd"\n'
        "trigger1 = (p2statetype = S) || (p2statetype = C)\n"
        'trigger2 = command = "holdback"\n'
        "trigger2 = (p2statetype = S) || (p2statetype = C)\n\n" % spec["throw"])

    if spec["taunt"]:
        body.append(st("Taunt", spec["taunt"], "start",
                       "trigger1 = statetype != A\ntrigger1 = ctrl\n"))

    for nm, v, btn, extra in normals_entries(spec["normals"]):
        body.append(st(nm, v, btn, extra))

    text = buf[0] + cmds + "[Statedef -1]\n\n" + "".join(body)
    path = "assets/characters/" + spec["file"]
    open(path, "w").write(text)
    print("wrote", path)


if __name__ == "__main__":
    for nm, spec in SPECS.items():
        gen(nm, spec)
