def cmd_block(name, motion, time):
    s = f'[Command]\nname = "{name}"\ncommand = {motion}\n'
    if time:
        s += f"time = {time}\n"
    return s + "\n"


def st(name, value, motion, extra=""):
    return (f"[State -1, {name}]\ntype = ChangeState\nvalue = {value}\n"
            f'triggerall = command = "{motion}"\n{extra}')


