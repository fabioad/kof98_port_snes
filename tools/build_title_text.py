"""Black outline layer for the title-screen texts (BG3).

The title prompt and the credit keep the fight HUD font exactly as it is
(menufont.chr, 8x8 glyphs drawn by MtStr).  The glyphs fill 7x7 of their
cell, so their own outline is only on the right/bottom edge; a full ring
does not fit an 8x8 sprite.

This emits the ring as a *background* layer instead: for each line, the
glyphs' bodies are dilated by one pixel, cut into 8x8 2bpp tiles plus a
32x32 BG3 map, so the black ring sits behind the gold sprites.  The title
turns BG3 on with priority (BGMODE $09) only for this screen.

Outputs src/gen_menu/titlering.chr (tiles) and src/gen_menu/titlering.inc
(tile bases and the map placement).

usage: python3 tools/build_title_text.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MENUS = os.path.join(ROOT, "src/engine/menus.asm")
HUD_INC = os.path.join(ROOT, "build/gen_fight/hud.inc")
HUD_CHR = os.path.join(ROOT, "build/gen_fight/hud.chr")
DST = os.path.join(ROOT, "src/gen_menu")

CHARSET = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.!?:-/,()"
PITCH, ROWS = 8, 9                   # 1 px ring + 7 px glyph + 1 px ring
RING = 1                             # BG3 palette colour 1 = black
BG2_MAP = 0x1400                     # word address of the 32x32 BG2 map
                                     # ($1C00 is the opening video's)
BG2_PAL = 4                          # CGRAM 64..79: unused by the title art
PRIO = 0x2000 | (BG2_PAL << 10)       # BG2 tile: priority + its own palette

# screen position of each line's ring: x, y (MtStr still draws the glyphs)
LINES = ((47, 151), (15, 205))


def glyphs():
    """charset index -> 8x8 body mask from the fight HUD font."""
    data = open(HUD_CHR, "rb").read()
    out = []
    for n in range(len(CHARSET)):
        raw = data[n * 16:(n + 1) * 16]
        out.append([[(raw[y * 2] >> (7 - x) & 1) |
                     ((raw[y * 2 + 1] >> (7 - x) & 1) << 1) == 3
                     for x in range(8)] for y in range(8)])
    return out


def read_strings():
    """(press, credit) as charset indices, read from the engine data."""
    inc = open(HUD_INC).read()
    m = re.search(r"StrStart:\s*\.db ([^\n]+)", inc)
    press = [int(v) for v in m.group(1).split(",")]
    menus = open(MENUS).read()
    m = re.search(r"TitleCredit2:\s*\.db ([^\n]+)", menus)
    credit = [int(v) for v in m.group(1).split(",")]
    assert press[0] == len(press) - 1 and credit[0] == len(credit) - 1
    return press[1:], credit[1:]


def dilated(idxs, g):
    """Ring bitmap: the glyph bodies grown by one pixel."""
    width = len(idxs) * PITCH + 2
    body = [[0] * width for _ in range(ROWS)]
    for i, ch in enumerate(idxs):
        ox = 1 + i * PITCH
        for y in range(8):
            for x in range(8):
                if g[ch][y][x]:
                    body[1 + y][ox + x] = 1
    out = [[0] * width for _ in range(ROWS)]
    for y in range(ROWS):
        for x in range(width):
            if body[y][x]:
                for dy in (-1, 0, 1):
                    for dx in (-1, 0, 1):
                        yy, xx = y + dy, x + dx
                        if 0 <= yy < ROWS and 0 <= xx < width:
                            out[yy][xx] = 1
    return out


def enc4(cell):
    """8x8 -> 4bpp tile, colour index 1 (black in BG palette 4)."""
    out = bytearray()
    for plane in range(4):
        for y in range(8):
            bits = 0
            for x in range(8):
                if cell[y][x] and plane == 0:
                    bits |= 1 << (7 - x)
            out.append(bits)
    return bytes(out)


def main():
    g = glyphs()
    press_ids, credit_ids = read_strings()
    imgs = [dilated(press_ids, g), dilated(credit_ids, g)]

    tiles = bytearray()
    table = [[0] * 32 for _ in range(32)]        # 32x32 BG3 map words
    placed = []
    for (rx, ry), img in zip(LINES, imgs):
        cx, px = divmod(rx, 8)
        cy, py = divmod(ry, 8)
        cols = (px + len(img[0]) + 7) // 8
        base = len(tiles) // 16
        grid = [[0] * (cols * 8) for _ in range(16)]
        for y in range(ROWS):
            for x in range(len(img[0])):
                grid[py + y][px + x] = img[y][x]
        for trow in range(2):
            for tcol in range(cols):
                cell = [grid[trow * 8 + y][tcol * 8:tcol * 8 + 8]
                        for y in range(8)]
                if any(any(r) for r in cell):
                    table[cy + trow][cx + tcol] = PRIO | (base + trow * cols
                                                           + tcol)
                tiles += enc4(cell)
        placed.append((cx, cy, cols))

    open(os.path.join(DST, "titlering.chr"), "wb").write(bytes(tiles))
    inc = ["; generated by tools/build_title_text.py -- do not edit",
           f".DEFINE TITLE_RING_TILES {len(tiles) // 32}",
           "TitleRingMap:"]
    for row in table:
        inc.append("    .dw " + ",".join(f"${w:04X}" for w in row))
    open(os.path.join(DST, "titlering.inc"), "w").write("\n".join(inc) + "\n")
    print(f"title ring: {len(tiles) // 32} tiles, "
          f"press at {placed[0]}, credit at {placed[1]}")


if __name__ == "__main__":
    main()
