#!/usr/bin/env python3
"""Build an isolated MSU hardware diagnostic from existing release assets.

No production ROM, object, symbol file or MSU file is overwritten.
Run the normal PVSnesLib build first if its prerequisite objects are missing.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "build/msu_diag"
CHARSET = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.:!?'-/+>,@\""


def run(*args):
    result = subprocess.run([str(x) for x in args], cwd=ROOT,
                            text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    with (OUT / "build.log").open("a") as log:
        log.write(result.stdout)
    if result.returncode:
        print(result.stdout[-6000:])
        result.check_returncode()
    else:
        print("\n".join(line for line in result.stdout.splitlines()
                        if "WARNING: There is a SLOT" not in line))


def main():
    global OUT
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", type=int, choices=(1, 2, 3, 4), default=1)
    version = parser.parse_args().version
    suffix = str(version) if version >= 2 else ""
    folder = "msu_diag" + suffix
    stem = "kof98-msu-diag" + suffix
    OUT = ROOT / "build" / folder
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "build.log").write_text("")
    sdk = Path(re.search(r"PVSNESLIB_HOME\s*:?=\s*(.+)",
                         (ROOT / "build/pvsneslib.mk").read_text())[1].strip())
    msu = ROOT / "kof98-snes.msu"
    data = msu.read_bytes()
    defs = (ROOT / "build/gen_fight/msu1_bases.inc").read_text()
    layout = int(re.search(r"MSU_LAYOUT\s*=\s*\$([0-9A-Fa-f]+)", defs)[1], 16)
    if data[:10] != b"KOF98MSU" + layout.to_bytes(2, "little"):
        raise SystemExit("MSU layout does not match generated engine tables")
    # Use actual nonblank character graphics at low, middle and high offsets.
    names = ("RUGAL", "CHIZURU", "KEN")
    offsets = [int(re.search(rf"MSU_{name}_SLICE\s*=\s*(\d+)", defs)[1]) * 32768
               for name in names]
    sample_size = 1280
    methods = [0] * len(names)
    if version == 3:
        rugal, chizuru, ken = offsets
        names = ("R0", "R1", "HD", "C0", "C1", "C2", "K0", "K1")
        offsets = [rugal, rugal + 1024, 0, chizuru, chizuru, chizuru, ken, ken]
        methods = [0, 0, 0, 0, 1, 2, 0, 1]
        sample_size = 256
    elif version == 4:
        names = tuple(f"{i:02d}" for i in range(8))
        offsets = [0xFF00, 0x10000, 0x20000, 0x40000, 0x100000,
                   0x200000, 0x400000, 0x800000]
        methods = [0] * len(names)
        sample_size = 256
    inc = ["; generated by tools/build_msu_diag.py\nMsuDiagSamples:\n"]
    for i, offset in enumerate(offsets):
        sample = data[offset:offset + sample_size]
        if len(sample) != sample_size or (version != 4 and len(set(sample)) < 2):
            raise SystemExit(f"Invalid diagnostic sample: {names[i]}")
        (OUT / f"sample{i}.bin").write_bytes(sample)
        inc.append(f".dd ${offset:08X}\n.dl (MsuDiagExpected{i} & $FFFFFF)\n.db {methods[i]}\n")
    for i in range(len(names)):
        inc.append(f'MsuDiagExpected{i}: .INCBIN "{folder}/sample{i}.bin"\n')
    lines = ["MSU D1 CPU 0000 VRAM 0000", "REQ 0000 OK 0000 TO 0000",
             "P1 0000 P2 0000 ST 0000", "POS 00000000 LEN 0000 B 0000"]
    # Derive columns from labels to avoid silent off-by-one field placement.
    fields = [("MD_CPU", 0, lines[0].index("CPU ") + 4),
              ("MD_VRAM", 0, lines[0].index("VRAM ") + 5),
              ("MD_REQ", 1, 4), ("MD_READY", 1, lines[1].index("OK ") + 3),
              ("MD_TO", 1, lines[1].index("TO ") + 3),
              ("MD_P1", 2, 3), ("MD_P2", 2, lines[2].index("P2 ") + 3),
              ("MD_STAT", 2, lines[2].index("ST ") + 3),
              ("MD_POS+2", 3, 4), ("MD_POS", 3, 8),
              ("MD_LEN", 3, lines[3].index("LEN ") + 4),
              ("MD_BOOT", 3, lines[3].index("B ") + 2)]
    live_field = 0
    if version >= 2:
        lines = ["MSU D2 VIA RAM B 0000"]
        fields = [("MD_BOOT", 0, lines[0].index("B ") + 2)]
        for i, name in enumerate(("RUG", "CHI", "KEN")):
            row = len(lines)
            lines += [f"{name} C0000 M0000 V0000", "E 00000000 C 00000000",
                      "M 00000000 V 00000000"]
            base = f"MD_RES+{i * 32}"
            fields += [(base, row, 5), (base + "+2", row, 11),
                       (base + "+4", row, 17)]
            for delta, line, col in ((6, row + 1, 2), (10, row + 1, 13),
                                      (14, row + 2, 2), (18, row + 2, 13)):
                fields += [(base + f"+{delta}", line, col),
                           (base + f"+{delta + 2}", line, col + 4)]
        if version >= 3:
            lines = ["MSU D4 LIMIT B0000 SQ0000" if version == 4 else "MSU D3 SEEK B 0000"]
            fields = [("MD_BOOT", 0, 14)]
            if version == 4:
                fields += [("MD_SEQ_DONE", 0, 21)]
            for i, name in enumerate(names):
                row = len(lines)
                lines += [f"{name} 00000000 C0000 M0000 {'S' if version == 4 else 'V'}0000",
                          "E 00000000 M00000000 S00000000" if version == 4 else
                          "E 00000000 C00000000 M00000000"]
                base = f"MD_RES+{i * 32}"
                fields += [(base + "+30", row, 3), (base + "+28", row, 7),
                           (base, row, 13), (base + "+2", row, 19),
                           (base + "+4", row, 25)]
                snapshots = ((6, 2), (14, 12), (18, 22)) if version == 4 else ((6, 2), (10, 12), (14, 22))
                for delta, col in snapshots:
                    fields += [(base + f"+{delta}", row + 1, col),
                               (base + f"+{delta + 2}", row + 1, col + 4)]
        live_field = len(fields) * 4
        row = len(lines)
        lines += ["REQ 0000 OK 0000 TO 0000", "P1 0000 P2 0000 ST 0000",
                  "POS 00000000 LEN 0000"]
        fields += [("MD_REQ", row, 4), ("MD_READY", row, 12),
                   ("MD_TO", row, 20), ("MD_P1", row + 1, 3),
                   ("MD_P2", row + 1, 11), ("MD_STAT", row + 1, 19),
                   ("MD_POS+2", row + 2, 4), ("MD_POS", row + 2, 8),
                   ("MD_LEN", row + 2, 17)]
    inc.append(f".DEFINE MSU_DIAG_LIVE_FIELD {live_field}\nMsuDiagTemplate:\n")
    for line in lines:
        assert len(line) <= 32, line
        inc.append(".dw " + ",".join(f"${0x3C00 | CHARSET.index(c):04X}"
                                     for c in line.ljust(32)) + "\n")
    inc.append("MsuDiagFields:\n")
    for address, row, column in fields:
        inc.append(f".dw {address}, {row * 64 + column * 2}\n")
    inc.append("MsuDiagFieldsEnd:\nMsuDiagHex: .db " +
               ",".join(str(CHARSET.index(c)) for c in "0123456789ABCDEF") + "\n")
    (OUT / "generated.inc").write_text("".join(inc))
    obj = OUT / "fight_bridge.obj"
    flags = ["-D", "MSU_DIAG2"] if version >= 2 else []
    if version >= 3:
        flags += ["-D", "MSU_DIAG3"]
    if version == 4:
        flags += ["-D", "MSU_DIAG4"]
    run(sdk / "devkitsnes/bin/wla-65816", "-d", "-s", "-x", "-D", "MSU_DIAG", *flags,
        "-I", ".", "-I", "src", "-I", "build", "-o", obj,
        "src/snes/fight_bridge.asm")
    objects = [ROOT / "src/snes/main.obj", ROOT / "build/gen_audio/soundbank.obj",
               ROOT / "hdr.obj", ROOT / "src/snes/boot64.obj", obj]
    lib = sdk / "pvsneslib/lib/HiROM_FastROM"
    objects += [lib / name for name in ("crt0_snes.obj", "libc.obj", "libm.obj", "libtcc.obj")]
    for path in objects:
        if not path.is_file():
            raise SystemExit(f"Missing {path}; run make -f Makefile.pvsnes first")
    link = OUT / "linkfile"
    link.write_text("[objects]\n" + "\n".join(map(str, objects)) + "\n")
    rom = OUT / (stem + ".sfc")
    run(sdk / "devkitsnes/bin/wlalink", "-d", "-s", "-A", "-c", "-L", lib, link, rom)
    run(sys.executable, "tools/fix_checksum.py", rom)
    run(sys.executable, "tools/verify_pvsnes_rom.py", rom)
    target_msu = OUT / (stem + ".msu")
    shutil.copyfile(msu, target_msu.with_suffix(".msu.tmp"))
    target_msu.with_suffix(".msu.tmp").replace(target_msu)
    readme = OUT / "LEIA-ME.txt"
    shutil.copyfile(ROOT / f"docs/MSU_DIAG{suffix}_TESTE.md", readme)
    manifest = {"version": version, "rom": rom.name, "msu": target_msu.name,
                "samples": dict(zip(names, offsets)),
                "sample_size": sample_size, "methods": dict(zip(names, methods)),
                "sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                           for p in (rom, target_msu)}}
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    archive = ROOT / (stem + ".zip")
    with zipfile.ZipFile(archive.with_suffix(".zip.tmp"), "w", zipfile.ZIP_DEFLATED) as z:
        for path in (rom, target_msu, readme, OUT / "manifest.json"):
            z.write(path, path.name)
    archive.with_suffix(".zip.tmp").replace(archive)
    print(f"Diagnostic package: {archive}")


if __name__ == "__main__":
    main()
